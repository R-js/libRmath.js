import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import wabt from 'wabt';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.resolve(__dirname, '../src/lib/rng/wichmann-hill');
const watFile = path.join(srcDir, 'wichmann-hill.wat');

async function compile() {
    console.log(`Reading ${watFile}...`);
    const watContent = fs.readFileSync(watFile, 'utf8');

    console.log('Initializing wabt...');
    const wabtModule = await wabt();

    console.log('Parsing WAT...');
    let module;
    try {
        module = wabtModule.parseWat(watFile, watContent);
    } catch (e) {
        console.error('Error parsing WAT:', e);
        process.exit(1);
    }

    console.log('Converting to Binary...');
    const { buffer } = module.toBinary({
        log: true,
        write_debug_names: true
    });

    console.log('Generating Base64 TypeScript file...');
    const base64 = Buffer.from(buffer).toString('base64');
    const tsContent = `/* Auto-generated by scripts/compile-wat.mjs */
import base64ToBinary from '@lib/base64_to_binary';

const wasmBase64 = "${base64}";

let memoizedModule: WebAssembly.Module | null = null;

export function getWasmModule(): WebAssembly.Module {
    if (!memoizedModule) {
        const binary = base64ToBinary(wasmBase64);
        memoizedModule = new WebAssembly.Module(binary);
    }
    return memoizedModule;
}

export async function instantiateWasm(): Promise<WebAssembly.Instance> {
    const module = getWasmModule();
    return await WebAssembly.instantiate(module);
}

/**
 * Instantiate the WASM module with shared memory for bulk operations
 * @param memory - WebAssembly.Memory instance to share with the module
 * @returns WebAssembly.Instance with access to the shared memory
 */
export function instantiateWasmWithMemory(memory: WebAssembly.Memory): WebAssembly.Instance {
    const module = getWasmModule();
    return new WebAssembly.Instance(module, {
        env: { memory }
    });
}
`;
    const tsFile = path.join(srcDir, 'wasm-module.ts');
    fs.writeFileSync(tsFile, tsContent);
    console.log(`Written ${tsFile}`);

    console.log('Done!');
}

compile().catch(console.error);
